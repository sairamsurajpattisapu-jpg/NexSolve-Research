"""Dataset plug-in protocol; raw schemas remain dataset-specific."""
from __future__ import annotations

from typing import Any, Protocol, Sequence


class DatasetAdapter(Protocol):
    name: str

    def load(self, source: str) -> Sequence[Any]: ...
    def validate(self, records: Sequence[Any]) -> dict[str, Any]: ...
    def normalize(self, records: Sequence[Any]) -> Sequence[Any]: ...
    def temporalize(self, records: Sequence[Any], window_seconds: int) -> Sequence[Any]: ...
    def feature_schema(self) -> dict[str, list[str]]: ...
    def quality_report(self) -> dict[str, Any]: ...